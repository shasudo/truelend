import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { resolve } from "node:path";
import { spawnSync } from "node:child_process";

const app = process.argv[2];
const write = process.argv.includes("--write");
if (!new Set(["website", "admin", "partners"]).has(app)) {
  throw new Error("Usage: check-cloudflare-types.mjs <website|admin|partners>");
}

const root = resolve(import.meta.dirname, "..");
const appDirectory = resolve(root, "apps", app);
const trackedTypes = resolve(appDirectory, "cloudflare-env.d.ts");
const temporaryDirectory = mkdtempSync(resolve(tmpdir(), `truelend-${app}-types-`));
const generatedTypes = resolve(temporaryDirectory, "cloudflare-env.d.ts");
const emptyEnvironment = resolve(temporaryDirectory, "empty.env");

function portableGeneratedTypes(contents) {
  return contents
    .replace(
      /^\/\/ Generated by Wrangler.*$/m,
      "// Generated from wrangler.jsonc by scripts/check-cloudflare-types.mjs. Do not edit.",
    )
    .replace(
      /\n\tinterface GlobalProps \{\n\t\tmainModule: typeof import\("[^"]+"\);\n\t\}\n/,
      "\n",
    )
    .replace(
      "interface CloudflareEnv extends __BaseEnv_CloudflareEnv {}",
      "interface CloudflareEnv extends Cloudflare.Env {}",
    );
}

try {
  writeFileSync(emptyEnvironment, "");
  const command = process.platform === "win32" ? "pnpm.cmd" : "pnpm";
  const result = spawnSync(
    command,
    [
      "exec",
      "wrangler",
      "types",
      generatedTypes,
      "--env-interface",
      "CloudflareEnv",
      "--include-runtime",
      "false",
      "--env-file",
      emptyEnvironment,
    ],
    { cwd: appDirectory, encoding: "utf8" },
  );
  if (result.error) throw result.error;
  if (result.status !== 0) {
    process.stderr.write(result.stdout);
    process.stderr.write(result.stderr);
    throw new Error(`${app} Wrangler type generation failed`);
  }

  const actual = portableGeneratedTypes(readFileSync(generatedTypes, "utf8"));
  if (write) {
    writeFileSync(trackedTypes, actual);
    console.log(`✓ generated ${app} Cloudflare binding types from wrangler.jsonc`);
  } else {
    const expected = readFileSync(trackedTypes, "utf8");
    if (actual !== expected) {
      throw new Error(
        `${app} Cloudflare binding types are stale; run pnpm --filter @truelend/${app} cf-typegen`,
      );
    }
    console.log(`✓ ${app} Cloudflare binding types match wrangler.jsonc`);
  }
} finally {
  rmSync(temporaryDirectory, { recursive: true, force: true });
}
